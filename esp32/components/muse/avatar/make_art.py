#!/usr/bin/env python3
"""Turn npsc_art.png (the 128x128 NORTH POLE SANTA COMMUNICATOR
screen, drawn by design/make_screen.py) into npsc_art.h: RGB565 pixels (R in the high bits, the same packing
as the default avatar's to565(); LVGL and the panel driver handle byte order),
plus the two corner snowflakes' pixels for the state cue."""
import sys
from PIL import Image

src = sys.argv[1] if len(sys.argv) > 1 else "npsc_art.png"
im = Image.open(src).convert("RGB")
assert im.size == (128, 128), im.size
px = im.load()

def rgb565(r, g, b):
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)

FLAKE_BOXES = [(7, 7, 13, 13), (114, 7, 120, 13)]   # final.py: sprite(d,7,7,FLAKE) and (114,7)
flakes = []
for x0, y0, x1, y1 in FLAKE_BOXES:
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            if px[x, y] == (255, 255, 255):
                flakes.append((x, y, 0 if x0 < 64 else 1))
assert len(flakes) == 2 * 25, len(flakes)

out = ["/* Generated by make_art.py from npsc_art.png. Do not edit. */",
       "#pragma once", "#include <stdint.h>", "",
       "#define NPSC_W 128", "#define NPSC_H 128", "",
       "static const uint16_t NPSC_ART[NPSC_W * NPSC_H] = {"]
vals = [rgb565(*px[x, y]) for y in range(128) for x in range(128)]
for i in range(0, len(vals), 16):
    out.append("    " + ", ".join("0x%04x" % v for v in vals[i:i + 16]) + ",")
out += ["};", "", "/* Snowflake pixels: x, y, which flake (0 left, 1 right). */",
        "#define NPSC_FLAKE_N %d" % len(flakes),
        "static const uint8_t NPSC_FLAKE[NPSC_FLAKE_N][3] = {"]
for i in range(0, len(flakes), 8):
    out.append("    " + " ".join("{%d, %d, %d}," % f for f in flakes[i:i + 8]))
out += ["};", ""]
open("npsc_art.h", "w").write("\n".join(out))
print("wrote npsc_art.h:", len(vals), "pixels,", len(flakes), "flake pixels")
